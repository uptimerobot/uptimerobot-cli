import type { CliInvocation } from './cli-invocation.js';
import { formatInvocation } from './cli-invocation.js';
import { AGENT_SETUP_TAG } from './tag.js';

/**
 * The self-contained setup guide `uptimerobot init` writes to
 * `uptimerobot-setup.md`, and the single source of the discovery/setup
 * contract for v1.
 *
 * The published `ai/` skills still serve MCP and plugin users, but the wizard
 * does not depend on them: everything an agent needs to go from the scan to
 * verified monitors lives here, driven entirely through the `uptimerobot` CLI.
 * Because there is exactly one copy of the contract — this one — there is
 * nothing for a second copy to drift against.
 *
 * Every command the guide names is templated through the resolved invocation,
 * so a caller who arrived through `npx @uptimerobot/cli` is never handed a bare
 * `uptimerobot` their shell cannot run. Only the leading invocation is
 * templated; the flags after it are literal, which is why each fenced example
 * concatenates `cmd(...)` with its argument lines rather than interpolating the
 * whole command.
 *
 * This module builds a string and nothing else: it reads no files, reaches no
 * network, and has no side effects. `init` owns the marker wrapping and the
 * write, exactly as it does for the scan document.
 */

